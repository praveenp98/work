/**
 * Copies the site's stylesheets into the studio, scoped under ".rv" so they style the video and nothing else
 * (Remotion Studio shares the page with its own UI). Runs before every `npm run studio` and `npm run render`,
 * so the videos always wear the site's current CSS. Output: src/generated/site.css (gitignored).
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import postcss from "postcss";
import prefixer from "postcss-prefix-selector";

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, "..", "..", "..");
const SOURCES = ["app/globals.css", "app/connect.css"]; // same order as app/layout.tsx
const SCOPE = ".rv";

export async function prepare() {
  let out = `/* GENERATED by scripts/prepare.mjs from ${SOURCES.join(" + ")}. Do not edit. */\n`;
  for (const rel of SOURCES) {
    const css = fs.readFileSync(path.join(repo, rel), "utf8");
    const res = await postcss([
      prefixer({
        prefix: SCOPE,
        transform(prefix, selector, prefixed) {
          const s = selector.trim();
          if (/^(:root|html|body)$/.test(s)) return prefix;
          if (/^(html|body)\b/.test(s)) return `${prefix} ${s.replace(/^(html|body)\s*/, "")}`.trim();
          return prefixed;
        },
      }),
    ]).process(css, { from: undefined });
    out += `\n/* ${rel} */\n${res.css}\n`;
  }
  const dir = path.join(here, "..", "src", "generated");
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, "site.css"), out);
  return path.join(dir, "site.css");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) console.log(`site css -> ${path.relative(process.cwd(), await prepare())}`);
